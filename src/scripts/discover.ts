import { mkdirSync, writeFileSync } from "node:fs";
import { CANDIDATE_INTENTS } from "../lib/agent/planner.ts";
import { discoverCapabilities, fetchMinerPrices, fetchNetworkStatus } from "../lib/telegraph/discovery.ts";

// Regenerates docs/TELEGRAPH_CAPABILITIES.md and its JSON snapshot from the live node. It makes no payments.
const snapshot = await discoverCapabilities(CANDIDATE_INTENTS);
const network = await fetchNetworkStatus();
const USAGE: Record<string, string> = {
  CRYPTO_PRICE_USD: "Evidence row for symbols: market price. Verifies a bare symbol before further spending.",
  NEWS_SEARCH_GENERAL: "Evidence row for symbols: adverse media. Soft signals only.",
  FRAUD_DETECTION_GENERAL: "Evidence row for symbols: fraud screen. Structured verdict can raise HIGH RISK.",
  SMART_CONTRACT_AUDIT_GENERAL: "Evidence rows: contract audit (TxLens) and token controls (GoPlus). No published format, so only named fields are read.",
  TOKEN_HOLDER_COUNT_GENERAL: "Evidence row: holder count.",
  LIQUIDITY_DEPTH_VERIFY_GENERAL: "Evidence row: liquidity of the largest pool.",
  SANCTIONS_SCREENING_MATCH_GENERAL: "Evidence row: sanctions screen. Contract addresses and full names only.",
  WASH_TRADING_DETECTION_GENERAL: "Evidence row: wash trading, by on-chain scan. Contract addresses only.",
};
const rows: string[] = [];
for (const capability of snapshot.capabilities) {
  let pricing = "Not checked";
  let live = capability.miner_count > 0 ? "Live" : "Unavailable";
  let sample = capability.miners.map((m) => `${m.id} (${m.slug})`).slice(0, 3).join(", ");
  if (capability.miner_count > 0) {
    const miners = await fetchMinerPrices(capability.intent, 100);
    const prices = [...new Set(miners.map((m) => m.min_price_usdc).filter((p): p is number => typeof p === "number"))].sort((a, b) => a - b);
    pricing = prices.length ? `Floor ${prices[0]! / 1e6} to ${prices.at(-1)! / 1e6} USDC across ${miners.length} listed` : "Not listed";
    const active = miners.filter((m) => m.activation_status === "active").length;
    live = `Live: ${capability.miner_count} miners, ${active} of ${miners.length} sampled active`;
    if (miners.length) sample = miners.slice(0, 3).map((m) => `${m.id} (${m.slug})`).join(", ");
  }
  const params = capability.params ? capability.params.map((p) => `\`${p.name}\`${p.required ? " (required)" : ""}: ${p.type ?? "?"}`).join("; ") : "None published";
  rows.push(`| \`${capability.intent}\` | ${sample || "None"} | ${params} | ${pricing} | ${live} | ${USAGE[capability.intent] ?? ""} |`);
}
const doc = `# Telegraph capabilities

Generated by \`npm run discover\` from the live node. Do not edit by hand.

- **Discovered:** ${snapshot.discovered_at}
- **Node:** ${snapshot.node}
- **Network:** Ethereum Sepolia testnet (eip155:11155111)
- **Live intents:** ${snapshot.intent_count} (${network.intents_with_miners} with at least one miner)
- **Epoch:** ${network.epoch}

The agent re-reads this data at the start of every assessment, so this file is a record and not a dependency.

| Intent | Miner ID (examples) | Parameters | Pricing | Availability | Memo usage |
|---|---|---|---|---|---|
${rows.join("\n")}

## Reading the table

- **Pricing** is each miner's advertised floor (\`min_price_usdc\`). The amount actually charged is the floor times a demand multiplier, and the agent reads it from each HTTP 402 challenge.
- **Miner ID** values are examples. Requests go to \`POST /engine/v1/ask\`, and the network routes each one. The miner that answered is recorded from the response.
- **Payment:** x402 \`exact\` on \`eip155:11155111\`, in test USDC \`0xcc194e1a843B658526D0D5C431f670028582Ae17\`, to the Diamond \`0x3624EB012B5E998BB57B6bE6C9Cfc9c4bc5eb99b\`. The node also offers an \`escrow\` scheme, which this application does not use.

## Verified protocol behavior

| Behavior | How it was verified |
|---|---|
| An unpaid \`POST /engine/v1/ask\` returns 402 with base64 terms in \`PAYMENT-REQUIRED\` | Live request |
| The test USDC reads as symbol USDC, 6 decimals | Read from the contract |
| Default x402 spend controls refuse this token until it is allow-listed | Real library, and the docs |
| An unfunded wallet's signed payment gets a second 402 with \`insufficient_funds\` | Live request |
| \`signal_hash\` re-derives from \`GET /engine/v1/signal/{hash}\` | 12 of 12 public signals on 2026-11-06 |
| A routed \`200\` can hold an unusable answer, such as an HTML page | Seen in public signals, so the agent reads only shaped fields marked \`ok\` |
| \`SMART_CONTRACT_AUDIT_GENERAL\` publishes no schema despite having miners | Live schema endpoint. TxLens and GoPlus still return structured fields, seen in live purchases |
| \`TOKEN_HOLDER_COUNT_GENERAL\` gives a count only, and \`LIQUIDITY_DEPTH_VERIFY_GENERAL\` needs a pool address and returns no slippage | Live schema and live purchases |
| \`PAYMENT-RESPONSE\` and \`X-TELEGRAPH-RECEIPT\` on a paid 200 | Live purchases in assessment LRM-2026-3LC6 |
`;
mkdirSync("docs", { recursive: true });
writeFileSync("docs/TELEGRAPH_CAPABILITIES.md", doc);
writeFileSync("docs/capabilities-snapshot.json", JSON.stringify(snapshot, null, 2));
console.log(rows.join("\n"));
